#!/usr/bin/env python3
"""Reads aquaguard_trees.json -> mem/aquaguard_rom.sv + mem/aquaguard_rom_params.json.
Fixed point: features/thresholds = signed 20b, unit 1e-3 (round-half-away). Leaves/margin = Q8.24 signed.
Node word (43b) = {is_leaf[42], feat[41:37], data[36:15] signed22, child[14:0]}; no-child = child+1."""
import json, sys, math
import numpy as np
SRC = sys.argv[1] if len(sys.argv) > 1 else "aquaguard_trees.json"
OUT = sys.argv[2] if len(sys.argv) > 2 else "mem/aquaguard_rom.sv"
FEATS = json.load(open("feature_order.json"))
FRAC = 24; FSCALE = 1000
BASE = json.load(open("verification_config.json"))["base_margin"]
THR_P = json.load(open("config.json"))["threshold"]
T = json.load(open(SRC))
def q_thr(t):  # float32 threshold -> 1e-3 grid integer
    v = float(np.float32(t)) * FSCALE
    return int(math.floor(abs(v) + 0.5)) * (1 if v >= 0 else -1)
def q_leaf(l): return int(round(l * (1 << FRAC)))
words = []; roots = []
for t in T:
    nd = {n["node_id"]: n for n in t["nodes"]}
    root = t["nodes"][0]["node_id"]; assert root.endswith("-0")
    base = len(words); roots.append(base)
    addr = {root: 0}; order = [root]; nxt = 1; i = 0
    while i < len(order):                      # BFS, yes/no placed adjacent
        n = nd[order[i]]; i += 1
        if n["leaf"] is None:
            assert n["missing"] == n["no"]
            addr[n["yes"]] = nxt; addr[n["no"]] = nxt + 1
            order += [n["yes"], n["no"]]; nxt += 2
    assert len(order) == len(nd)
    for nid in order:
        n = nd[nid]
        if n["leaf"] is not None:
            w = (1 << 42) | ((q_leaf(n["leaf"]) & 0x3FFFFF) << 15)
        else:
            f = FEATS.index(n["feature"]); c = base + addr[n["yes"]]
            assert addr[n["no"]] == addr[n["yes"]] + 1
            w = (f << 37) | ((q_thr(n["threshold"]) & 0x3FFFFF) << 15) | c
        words.append(w)
N = len(words)
leaves = [q_leaf(n["leaf"]) for t in T for n in t["nodes"] if n["leaf"] is not None]
thr = [q_thr(n["threshold"]) for t in T for n in t["nodes"] if n["leaf"] is None]
assert max(thr) < 2**19 and min(thr) >= -2**19 and max(map(abs, leaves)) < 2**21 and N < 2**15
logit = math.log(THR_P / (1 - THR_P))
THR_SUM = round((logit - BASE) * (1 << FRAC))
with open(OUT, "w") as f:
    f.write("// GENERATED by scripts/generate_tree_rom.py - do not edit\n")
    f.write("module aquaguard_node_rom (input logic [14:0] addr, output logic [42:0] data);\n  always_comb begin\n    case (addr)\n")
    for a, w in enumerate(words): f.write(f"      15'd{a}: data = 43'h{w:011x};\n")
    f.write("      default: data = 43'h0;\n    endcase\n  end\nendmodule\n\n")
    f.write("module aquaguard_root_rom (input logic [8:0] tree, output logic [14:0] root);\n  always_comb begin\n    case (tree)\n")
    for t, r in enumerate(roots): f.write(f"      9'd{t}: root = 15'd{r};\n")
    f.write("      default: root = 15'd0;\n    endcase\n  end\nendmodule\n")
json.dump({"num_nodes": N, "roots": roots, "words": words, "thr_sum": THR_SUM, "logit": logit}, open("mem/aquaguard_rom_params.json", "w"))
print(f"nodes={N} trees={len(roots)} max_thr={max(thr)} min_thr={min(thr)} leaf[{min(leaves)},{max(leaves)}] ({min(leaves)/2**FRAC:.6f},{max(leaves)/2**FRAC:.6f})")
print(f"logit(0.12)={logit:.9f} base={BASE} THR_SUM(Q8.24)={THR_SUM} = {THR_SUM/2**FRAC:.9f}")
